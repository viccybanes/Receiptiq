import assert from 'node:assert/strict'
import path from 'node:path'
import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({viewport:{width:1440,height:900}})
const base = process.env.RECEIPTIQ_TEST_URL || 'http://127.0.0.1:8766'
try {
  await page.goto(base)
  await page.getByRole('heading',{name:'Add expense',exact:true}).waitFor()
  const uploaded = page.waitForResponse(r=>r.request().method()==='POST' && new URL(r.url()).pathname==='/api/v1/receipts')
  await page.getByLabel('Choose receipt images').setInputFiles(path.resolve('../artifacts/samples/001-printed.png'))
  const id=(await (await uploaded).json()).id
  await page.locator(`[data-receipt-id="${id}"]`).click()
  await page.waitForFunction(()=>document.querySelector('[data-field="supplier"]')?.value==='Riverside Industrial Supply')
  await page.waitForFunction(()=>document.querySelector('.image-panel img')?.naturalWidth>0)
  await page.waitForTimeout(200)
  await page.screenshot({path:'../artifacts/ui-overhaul-desktop.png',fullPage:true})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No desktop horizontal overflow')
  assert.ok(await page.evaluate(()=>document.documentElement.scrollHeight<=innerHeight+1),'Desktop must fit viewport')
  await page.getByRole('searchbox',{name:'Find a receipt'}).fill('does not exist')
  await page.getByText('No receipts match these filters.',{exact:true}).waitFor()
  await page.getByRole('searchbox',{name:'Find a receipt'}).fill('Riverside')
  assert.ok(await page.locator(`[data-receipt-id="${id}"]`).isVisible())
  await page.getByRole('searchbox',{name:'Find a receipt'}).fill('')
  const fields=page.locator('.fields-panel'), stage=page.locator('.image-stage')
  const before=await stage.boundingBox()
  await fields.evaluate(el=>el.scrollTop=500)
  assert.equal((await stage.boundingBox()).y,before.y)
  await fields.evaluate(el=>el.scrollTop=0)
  for(let i=0;i<4;i++) await page.getByRole('button',{name:'Zoom in',exact:true}).click()
  const bounds=await stage.boundingBox()
  await page.mouse.move(bounds.x+bounds.width*.7,bounds.y+bounds.height*.7)
  await page.mouse.down(); await page.mouse.move(bounds.x+bounds.width*.3,bounds.y+bounds.height*.3,{steps:5}); await page.mouse.up()
  assert.ok(await stage.evaluate(el=>el.scrollLeft>0 && el.scrollTop>0))
  await page.getByRole('button',{name:'Reset view',exact:true}).click()
  await page.locator('.receipt-tools > summary').click()
  const toolsBounds = await page.locator('.receipt-tools').boundingBox()
  const panelBounds = await page.locator('.image-panel').boundingBox()
  assert.ok(toolsBounds.y >= panelBounds.y && toolsBounds.y + toolsBounds.height <= panelBounds.y + panelBounds.height + 1,
    'Expanded tools must remain inside the viewer')
  await page.getByRole('button',{name:'Select region',exact:true}).click()
  assert.equal(await page.locator('.receipt-tools').getAttribute('open'),null)
  assert.ok(await page.getByRole('img',{name:'Drag to select receipt region'}).isVisible())
  await page.locator('.receipt-tools > summary').click()
  await page.getByRole('button',{name:'Select region',exact:true}).click()
  await page.locator('.receipt-tools > summary').click()
  assert.ok(await page.getByRole('button',{name:'Run OCR',exact:true}).isVisible())
  await page.locator('.receipt-tools > summary').click()
  await page.locator('[data-field="items.0.quantity"]').fill('2')
  assert.equal(await page.locator('[data-field="items.0.line_total"]').inputValue(),'2400.00')
  await page.locator('[data-field="items.0.quantity"]').fill('1')
  await page.locator('[data-field="items.0.item_type"]').selectOption('Equipment')
  await page.waitForTimeout(1000)
  for(const [width,height] of [[1024,768],[768,1024],[375,812],[812,375]]) {
    await page.setViewportSize({width,height})
    await page.screenshot({path:`../artifacts/ui-overhaul-${width}.png`,fullPage:true})
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`No overflow at ${width}`)
  }
  await page.setViewportSize({width:1440,height:900})
  await page.emulateMedia({reducedMotion:'reduce'})
  assert.equal(await page.getByRole('button',{name:'Zoom in',exact:true}).evaluate(el=>getComputedStyle(el).transitionDuration),'0s')
  await page.getByRole('button',{name:'Settings',exact:true}).click()
  await page.screenshot({path:'../artifacts/ui-overhaul-settings.png',fullPage:true})
  for(const name of ['CSV formats','Backups','Local models']) await page.getByRole('tab',{name,exact:true}).click()
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('dialog[open]').count(),0)
  await page.getByLabel(/Photo of item purchased/).first().setInputFiles(path.resolve('../artifacts/samples/001-printed.png'))
  await page.getByRole('button',{name:'Remove photo',exact:true}).first().waitFor()
  await page.getByRole('textbox',{name:'Reviewed by',exact:true}).fill('UI QA')
  await page.getByRole('button',{name:'Save now',exact:true}).click()
  for(const checkbox of await page.locator('.validation-panel input[type=checkbox]').all()) await checkbox.check()
  const reason = page.getByRole('textbox',{name:'Reason for accepting warnings',exact:true})
  if(await reason.count()) await reason.fill('Synthetic receipt used for interface verification.')
  const verified = page.waitForResponse(r=>r.request().method()==='POST' && new URL(r.url()).pathname.endsWith('/verify'))
  await page.getByRole('button',{name:'Verify receipt',exact:true}).click()
  assert.equal((await verified).status(),200)
  await page.getByRole('button',{name:'Select all verified',exact:true}).click()
  await page.getByRole('button',{name:'Preview CSV',exact:true}).click()
  await page.getByRole('heading',{name:'Check your CSV',exact:true}).waitFor()
  const download = page.waitForEvent('download')
  await page.getByRole('button',{name:'Download CSV + photos',exact:true}).click()
  const bundle = await download
  assert.equal(await bundle.failure(),null)
  await bundle.saveAs('../artifacts/ui-overhaul-export.zip')
  await page.locator('.export-dialog').waitFor({state:'detached'})
  const imported = page.waitForResponse(r=>r.request().method()==='POST' && new URL(r.url()).pathname==='/api/v1/imports')
  await page.getByLabel('Choose CSV or ZIP and optional photos').setInputFiles('../artifacts/ui-overhaul-export.zip')
  assert.equal((await imported).status(),201)
  console.log('PASS: item photo, verification, CSV preview, ZIP download and re-import, settings tabs and Escape')
  console.log('PASS: desktop fit, responsive layouts, search, independent scroll, pan/reset, region tools, arithmetic/category edit, reduced motion, settings')
} finally { await browser.close() }
