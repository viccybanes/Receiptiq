import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import ts from 'typescript'
const source = await fs.readFile(new URL('../src/amount.ts', import.meta.url), 'utf8')
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ES2020 } })
const { completeAmounts } = await import('data:text/javascript;base64,' + Buffer.from(compiled.outputText).toString('base64'))
const receipt = (quantity, unit_price, line_total, total = '') => ({ total, items: [{ id: 'a', quantity, unit_price, line_total }] })
let data = completeAmounts(receipt('3', '0.10', ''))
assert.equal(data.items[0].line_total, '0.30')
assert.equal(data.total, '0.30')
assert.equal(completeAmounts(receipt('', '25', '100')).items[0].quantity, '4')
assert.equal(completeAmounts(receipt('4', '', '100')).items[0].unit_price, '25.00')
assert.equal(completeAmounts(receipt('', '0', '100')).items[0].quantity, '')
let changed = structuredClone(data); changed.items[0].quantity = '5'
changed = completeAmounts(changed, data)
assert.equal(changed.items[0].line_total, '0.50')
assert.equal(changed.total, '0.50')
const discount = completeAmounts(receipt('3', '10', '25', '20'))
assert.equal(discount.items[0].line_total, '25')
assert.equal(discount.total, '20')
assert.equal(completeAmounts(receipt('bad', '2', '')).total, '')
const amountChange = completeAmounts(receipt('3', '0.10', '1.00', '0.30'), data)
assert.equal(amountChange.items[0].quantity, '10')
assert.equal(amountChange.total, '1.00')
assert.equal(completeAmounts({total: '', items: [{id:'a', quantity:'', unit_price:'', line_total:'10'}, {id:'b', quantity:'', unit_price:'', line_total:''}]}).total, '')
console.log('PASS: missing arithmetic, live edits, exact cents, zero division, incomplete rows, discounts')

assert.equal(completeAmounts(receipt('', '30', '100')).items[0].quantity, '')
assert.equal(completeAmounts(receipt('2.000000', '25', '')).items[0].quantity, '2')
assert.equal(completeAmounts(receipt('1.5', '25', '')).items[0].line_total, '')
const discounted = receipt('3', '10', '30', '30')
assert.equal(completeAmounts(receipt('3', '10', '25', '30'), discounted).items[0].quantity, '3')
console.log('PASS: whole quantities only; fractional inference stays unresolved, existing discounts preserved')

let percentages = { total: '300.00', items: [
  { id: 'a', quantity: '2', unit_price: '100', line_total: '200.00' },
  { id: 'b', quantity: '1', unit_price: '100', line_total: '100.00', discount_percent: '0' },
] }
const percentEdit = (data, percent) => completeAmounts({ ...data, total_discount_percent: percent }, data)
percentages = percentEdit(percentages, '10')
assert.deepEqual(percentages.items.map(item => item.line_total), ['180.00', '100.00'])
assert.equal(percentages.total, '280.00')
percentages = percentEdit(percentages, '20')
assert.deepEqual(percentages.items.map(item => item.line_total), ['160.00', '100.00'])
assert.equal(percentages.total, '260.00')
assert.deepEqual(percentages.items.map(item => item.unit_price), ['100', '100'])
const overridden = completeAmounts({ ...percentages, items: percentages.items.map((item, index) =>
  index === 0 ? { ...item, discount_percent: '5' } : item) }, percentages)
assert.equal(overridden.total, '290.00')
const reordered = percentEdit({ ...overridden, items: [...overridden.items].reverse() }, '50')
assert.deepEqual(reordered.items.map(item => item.line_total), ['100.00', '190.00'])
const cleared = completeAmounts({ ...reordered, items: reordered.items.map(item => ({ ...item, discount_percent: '' })) }, reordered)
assert.equal(cleared.total, '150.00')
assert.equal(percentEdit(cleared, '').total, '300.00')
const added = completeAmounts({ ...cleared, items: [...cleared.items,
  { id: 'new', quantity: '3', unit_price: '0.05', line_total: '' }] }, cleared)
assert.equal(added.items[2].line_total, '0.08')
assert.equal(added.total, '150.08')
assert.deepEqual(completeAmounts(added), added, 'Reload must not compound the discount')
const factors = completeAmounts({ ...cleared, items: cleared.items.map(item => ({ ...item, quantity: '4' })) }, cleared)
assert.equal(factors.total, '400.00')
assert.equal(percentEdit(cleared, '100').total, '0.00')
for (const percent of ['-1', '101', 'NaN', '1e1', '10%', '1.1234567'])
  assert.equal(percentEdit(cleared, percent).items[0].line_total, '50.00', 'Invalid drafts must not corrupt money')
const fraction = percentEdit(receipt('3', '0.05', '0.15', '0.15'), '10')
assert.equal(fraction.items[0].line_total, '0.14')
assert.equal(fraction.total, '0.14')
const missing = percentEdit(receipt('', '100', '150', '150'), '50')
assert.equal(missing.items[0].quantity, '', 'A new discount must not reinterpret an old Amount as net')
console.log('PASS: percentage inheritance, overrides, zero, clear, reorder, insertion, rounding and no compounding')
